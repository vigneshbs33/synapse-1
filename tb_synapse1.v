                    u_dut.score[2] !== exp_s[2]) begin
                    $display("INTERNAL CHECK FAIL: class scores differ from trainer model");
                    $display("RESULT: FAIL");
                    $finish;
                end
                $display("  internal check: hidden activations + class scores bit-identical to trainer model");
            end
            @(negedge clk);
        end
    endtask

