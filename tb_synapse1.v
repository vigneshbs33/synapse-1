    task run_image(input integer idx);
        begin
            $write("image %2d:\n", idx);
            for (r = 0; r < 8; r = r + 1) begin
                $write("  ");
                for (c = 0; c < 8; c = c + 1) begin
                    p = img[idx*64 + r*8 + c];
                    if (p > 160) $write("#");
                    else if (p > 96) $write("+");
                    else if (p > 32) $write(".");
                    else $write(" ");
                end
                $write("\n");
            end
            @(negedge clk); start = 1; @(negedge clk); start = 0;
            for (k = 0; k < 64; k = k + 1) begin
                @(negedge clk);
                while (!pix_ready) @(negedge clk);
                pix_data = img[idx*64 + k]; pix_valid = 1;
            end
            @(negedge clk); pix_valid = 0;
            guard = 0;
            while (!done && guard < 20000) begin @(negedge clk); guard = guard + 1; end
            if (!done) begin
                $display("  TIMEOUT waiting for done");
                $display("RESULT: FAIL");
                $finish;
            end
            if (digit == exp_label[idx]) begin
                $display("  PREDICTED %0d  EXPECTED %0d  PASS  (latency %0d cycles = %0d ns @ 100 MHz)",
                         digit, exp_label[idx], cycles_o, cycles_o * 10);
                correct = correct + 1;
            end else begin
                $display("  PREDICTED %0d  EXPECTED %0d  FAIL", digit, exp_label[idx]);
            end
            if (idx == 0) begin
                if (u_dut.hact[0] !== exp_h[0] || u_dut.hact[1] !== exp_h[1] ||
                    u_dut.hact[2] !== exp_h[2] || u_dut.hact[3] !== exp_h[3]) begin
                    $display("INTERNAL CHECK FAIL: hidden activations differ from trainer model");
                    $display("RESULT: FAIL");
